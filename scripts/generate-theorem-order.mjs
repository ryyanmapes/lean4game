import { readFile, writeFile } from 'node:fs/promises'

const repositoryRoot = new URL('../', import.meta.url)
const generatedFile = new URL('../client/src/visual/theoremOrder.generated.ts', import.meta.url)

async function readEntries(filename) {
  const contents = await readFile(new URL(filename, repositoryRoot), 'utf8')
  const entries = []
  const seenNames = new Set()

  for (const [index, rawLine] of contents.split(/\r?\n/u).entries()) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue

    const fields = line.split('|').map(field => field.trim())
    if (fields.length !== 3 || fields.some(field => !field)) {
      throw new Error(`${filename}:${index + 1}: expected category | name | statement`)
    }

    const [category, name, statement] = fields
    if (seenNames.has(name)) {
      throw new Error(`${filename}:${index + 1}: duplicate theorem name ${name}`)
    }
    seenNames.add(name)
    entries.push({ category, name, statement })
  }

  return entries
}

function renderEntries(exportName, entries) {
  const rows = entries.map(entry => `  ${JSON.stringify(entry)},`).join('\n')
  return `export const ${exportName} = [\n${rows}\n] as const\n`
}

const transformEntries = await readEntries('all_transforms.txt')
const combiningEntries = await readEntries('all_theorems.txt')
const output = `// Generated by scripts/generate-theorem-order.mjs.
// Edit all_transforms.txt and all_theorems.txt, not this file.

${renderEntries('TRANSFORM_THEOREM_ENTRIES', transformEntries)}
${renderEntries('COMBINING_THEOREM_ENTRIES', combiningEntries)}
export const TRANSFORM_THEOREM_ORDER: readonly string[] =
  TRANSFORM_THEOREM_ENTRIES.map(entry => entry.name)

export const COMBINING_THEOREM_ORDER: readonly string[] =
  COMBINING_THEOREM_ENTRIES.map(entry => entry.name)
`

let previous = ''
try {
  previous = await readFile(generatedFile, 'utf8')
} catch (error) {
  if (error?.code !== 'ENOENT') throw error
}

if (previous !== output) await writeFile(generatedFile, output, 'utf8')
